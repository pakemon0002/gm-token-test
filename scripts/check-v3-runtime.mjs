import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {runInContext} from 'node:vm';
const require=createRequire(import.meta.url);
const {JSDOM,VirtualConsole}=require(process.env.GM_DOM_MODULE||'jsdom');
const root=new URL('../miniapp/public/',import.meta.url);
const read=p=>readFileSync(new URL(p,root),'utf8');
const errors=[];
const virtualConsole=new VirtualConsole();
virtualConsole.on('jsdomError',err=>errors.push(err));
const dom=new JSDOM('<!doctype html><html><body><div id="root"></div><div id="test-v3"></div></body></html>',{url:'https://gm-test.invalid/',runScripts:'outside-only',pretendToBeVisual:true,virtualConsole});
const w=dom.window;
try{
 w.fetch=async()=>{throw Error('Network disabled in isolated render test')};
 w.matchMedia=()=>({matches:false,addListener(){},removeListener(){}});
 const ctx=dom.getInternalVMContext();
 for(const p of ['vendor/react.production.min.js','vendor/react-dom.production.min.js'])runInContext(read(p),ctx,{filename:p});
 assert.equal(w.React.version,'16.0.0');
 runInContext(read('main.js')+'\nwindow.__v3Test={V3Scene,V3Catalog,V3ProfileArt};',ctx,{filename:'main.js'});
 assert.ok(w.document.getElementById('root').childElementCount>0,'App must render instead of showing blank screen');
 const host=w.document.getElementById('test-v3');
 const el=(c,p)=>w.React.createElement(c,p);
 const click=node=>node.dispatchEvent(new w.MouseEvent('click',{bubbles:true}));
 let currentModel='',disposed=0,active=false;
 w.GM_MODELS={};w.GMViewer={mount(canvas,model){currentModel=model;return {setModel(m){currentModel=m},setActive(v){active=v},dispose(){disposed++}}}};
 w.ReactDOM.render(el(w.__v3Test.V3Scene,{gpu:'4060',running:true}),host);
 assert.ok(host.querySelector('.v3-gpu-render'),'2D scene mounts under actual bundled React');
 click(host.querySelector('.v3-mode button:nth-child(2)'));
 await new Promise(r=>setTimeout(r,30));
 assert.ok(host.querySelector('canvas'),'3D toggle renders canvas');
 assert.equal(currentModel,'rig-live');assert.equal(active,true);
 click(host.querySelector('.v3-mode button:nth-child(1)'));
 assert.equal(disposed,1,'switching to 2D releases renderer');
 w.ReactDOM.render(el(w.__v3Test.V3Catalog,{}),host);
 click(host.querySelector('.v3-catalog-grid button:last-child'));
 assert.match(host.querySelector('.v3-gpu-render').src,/gpu-4090\.png$/);
 w.ReactDOM.render(el(w.__v3Test.V3ProfileArt,{userId:'runtime-test'}),host);
 click(host.querySelector('.v3-avatar-edit'));click(host.querySelector('.v3-avatar-picker button:nth-child(2)'));
 assert.equal(w.localStorage.getItem('gm_v3_avatar_runtime-test'),'cyborg');
 assert.match(host.querySelector('.v3-avatar img').src,/avatar-cyborg\.png$/);
 w.ReactDOM.unmountComponentAtNode(host);
 assert.equal(errors.length,0,errors.map(e=>e.message).join('\n'));
 console.log('PASS: bundled React 16 root, V3 scene, 2D/3D lifecycle, catalogue and avatar rendering');
}finally{w.close()}
