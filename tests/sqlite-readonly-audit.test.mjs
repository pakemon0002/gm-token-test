import test from 'node:test';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {spawnSync} from 'node:child_process';
import {mkdtempSync,rmSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
const script=new URL('../scripts/audit-sqlite-readonly.mjs',import.meta.url).pathname;
test('production readiness inventory is read-only, aggregated and rejects negative game balances',t=>{
 const dir=mkdtempSync(join(tmpdir(),'gm-readonly-inventory-'));t.after(()=>rmSync(dir,{recursive:true,force:true}));
 const path=join(dir,'game.sqlite');
 const db=new DatabaseSync(path);
 db.exec("CREATE TABLE users(id TEXT PRIMARY KEY);CREATE TABLE wallets(user_id TEXT PRIMARY KEY REFERENCES users(id),gm INTEGER,cr INTEGER,vault INTEGER);CREATE TABLE pools(name TEXT PRIMARY KEY,gm INTEGER,cr INTEGER);CREATE TABLE points_account(user_id TEXT PRIMARY KEY,points INTEGER)");
 db.prepare('INSERT INTO users(id) VALUES(?)').run('private-user-identifier');
 db.prepare('INSERT INTO wallets VALUES(?,?,?,?)').run('private-user-identifier',500,100,25);
 db.prepare('INSERT INTO pools VALUES(?,?,?)').run('DAILY',2000,0);
 db.prepare('INSERT INTO points_account VALUES(?,?)').run('private-user-identifier',100);
 db.close();
 const run=()=>spawnSync(process.execPath,['--experimental-sqlite',script,path],{encoding:'utf8'});
 const good=run();assert.equal(good.status,0,good.stderr);
 const result=JSON.parse(good.stdout);
 assert.equal(result.ok,true);assert.equal(result.baseline.currencyTotals.wallets_gm_cents,500);
 assert.equal(result.baseline.counts.users,1);
 assert.equal(typeof result.fingerprint,'string');assert.equal(result.fingerprint.length,64);
 assert.ok(!good.stdout.includes('private-user-identifier'),'no player identifiers exposed');
 const bad=new DatabaseSync(path);bad.prepare('UPDATE points_account SET points=-1').run();bad.close();
 const failed=run();assert.equal(failed.status,1);
 assert.equal(JSON.parse(failed.stdout).baseline.badValues.points,1);
 const verify=new DatabaseSync(path,{readOnly:true});
 assert.equal(verify.prepare('SELECT points FROM points_account').get().points,-1,'audit never mutates');
 verify.close();
});
